const ASSET_MATCHERS = {
  windows: (name) => /\.exe$/i.test(name) && /setup/i.test(name),
  "windows-portable": (name) => /\.exe$/i.test(name) && /portable/i.test(name),
  "linux-appimage": (name) => /\.appimage$/i.test(name),
  "linux-deb": (name) => /\.deb$/i.test(name) && /control-center/i.test(name),
  "linux-agent-deb": (name) => /\.deb$/i.test(name) && /agent/i.test(name),
};
const OFFICIAL_RELEASE_REPOSITORY = "AnxLabs/AnxOS-Control-Center-Releases";
const RELEASE_DOWNLOAD_PREFIX = `https://github.com/${OFFICIAL_RELEASE_REPOSITORY}/releases/download/`;

// GitHub's API allows 60 unauthenticated requests an hour per IP, and the
// Worker's outbound IPs are shared, so an uncached lookup per download was
// refused with 403 about half the time (seen as a 502 on 2026-11-27). The
// list is reused for RELEASES_FRESH_MS and, when GitHub refuses, a stale copy
// (up to RELEASES_STALE_MS) or the stable release this deployment's config.js
// names is used instead.
const RELEASES_FRESH_MS = 5 * 60 * 1000;
const RELEASES_STALE_MS = 7 * 24 * 60 * 60 * 1000;
const RELEASES_CACHE_PATH = "/__anx-cache/github-releases-v1";
let memoryReleases = null;

function json(body, status, extraHeaders = {}) {
  return new Response(JSON.stringify(body), { status, headers: { "content-type": "application/json; charset=utf-8", "cache-control": "no-store", ...extraHeaders } });
}

function isOfficialAssetUrl(value) {
  return String(value || "").startsWith(RELEASE_DOWNLOAD_PREFIX);
}

function edgeCache() {
  try {
    return typeof caches !== "undefined" && caches.default ? caches.default : null;
  } catch {
    return null;
  }
}

async function readCachedReleases(cacheKey) {
  if (memoryReleases) return memoryReleases;
  const cache = edgeCache();
  if (!cache) return null;
  try {
    const hit = await cache.match(cacheKey);
    if (!hit) return null;
    const fetchedAt = Number(hit.headers.get("x-anx-fetched-at"));
    const releases = await hit.json();
    if (!Number.isFinite(fetchedAt) || !Array.isArray(releases)) return null;
    memoryReleases = { fetchedAt, releases };
    return memoryReleases;
  } catch {
    return null;
  }
}

async function storeReleases(cacheKey, releases, now, ctx) {
  memoryReleases = { fetchedAt: now, releases };
  const cache = edgeCache();
  if (!cache) return;
  const stored = new Response(JSON.stringify(releases), {
    headers: { "content-type": "application/json", "cache-control": `max-age=${Math.floor(RELEASES_STALE_MS / 1000)}`, "x-anx-fetched-at": String(now) },
  });
  const write = cache.put(cacheKey, stored).catch(() => {});
  if (ctx && typeof ctx.waitUntil === "function") ctx.waitUntil(write);
  else await write;
}

// Returns { releases, source } or { error, status }.
async function loadReleases(request, env, ctx) {
  const now = Date.now();
  const cacheKey = new Request(new URL(RELEASES_CACHE_PATH, request.url).toString());
  const cached = await readCachedReleases(cacheKey);
  if (cached && now - cached.fetchedAt < RELEASES_FRESH_MS) return { releases: cached.releases, source: "cache" };
  const headers = { accept: "application/vnd.github+json", "user-agent": "AnxHost-website-downloads" };
  if (env.ANXOS_GITHUB_TOKEN) headers.authorization = `Bearer ${env.ANXOS_GITHUB_TOKEN}`;
  let status = 0;
  try {
    const response = await fetch(`https://api.github.com/repos/${OFFICIAL_RELEASE_REPOSITORY}/releases?per_page=20`, { headers });
    status = response.status;
    if (response.ok) {
      const releases = await response.json();
      if (Array.isArray(releases)) {
        await storeReleases(cacheKey, releases, now, ctx);
        return { releases, source: "github" };
      }
    }
  } catch {}
  if (cached && now - cached.fetchedAt < RELEASES_STALE_MS) return { releases: cached.releases, source: "stale-cache" };
  return { error: "release_source_unavailable", status };
}

function pickAsset(releases, select, allowPrerelease) {
  // Stable/latest downloads must never resolve an RC to a prerelease. A prerelease is
  // only served when a caller explicitly opts in with ?prerelease=1.
  const release = (Array.isArray(releases) ? releases : [])
    .filter((item) => item && !item.draft && (allowPrerelease || !item.prerelease))
    .sort((left, right) => new Date(right.published_at || right.created_at || 0) - new Date(left.published_at || left.created_at || 0))
    .find((item) => (item.assets || []).some((candidate) => select(candidate.name || "") && isOfficialAssetUrl(candidate.browser_download_url)));
  return release?.assets?.find((candidate) => select(candidate.name || "") && isOfficialAssetUrl(candidate.browser_download_url)) || null;
}

// The stable release this deployment was promoted with (config.js is only
// regenerated by the stable promotion), used when GitHub cannot be asked.
async function stableAssetFromConfig(request, env, select) {
  try {
    const response = await env.ASSETS.fetch(new Request(new URL("/config.js", request.url).toString()));
    if (!response.ok) return null;
    const source = await response.text();
    for (const match of source.matchAll(/url:\s*"([^"]+)"/g)) {
      const url = match[1];
      const fileName = decodeURIComponent(url.split("/").pop() || "");
      if (isOfficialAssetUrl(url) && select(fileName)) return url;
    }
  } catch {}
  return null;
}

async function latestDownload(request, env, platform, ctx) {
  const select = ASSET_MATCHERS[platform];
  if (!select) return json({ error: "unsupported_platform" }, 404);
  let allowPrerelease = false;
  try {
    allowPrerelease = ["1", "true", "yes"].includes(String(new URL(request.url).searchParams.get("prerelease") || "").toLowerCase());
  } catch {}
  const configured = env.ANXOS_RELEASE_REPOSITORY || env.ANXOS_GITHUB_REPOSITORY || OFFICIAL_RELEASE_REPOSITORY;
  const match = String(configured).trim().match(/^([^/]+)\/([^/]+)$/);
  if (!match || `${match[1]}/${match[2]}` !== OFFICIAL_RELEASE_REPOSITORY) return json({ error: "release_repository_not_configured" }, 500);
  const loaded = await loadReleases(request, env, ctx);
  let location = loaded.releases ? pickAsset(loaded.releases, select, allowPrerelease)?.browser_download_url : null;
  if (!location && loaded.error && !allowPrerelease) location = await stableAssetFromConfig(request, env, select);
  if (location) return new Response(null, { status: 302, headers: { location, "cache-control": "no-store" } });
  if (loaded.error) return json({ error: loaded.error, status: loaded.status }, 503, { "retry-after": "60" });
  return json({ error: "release_asset_unavailable" }, 404);
}

// Hosts. anxhost.anxlabs.net is the AnxHost website; anxoscontrolcenter.org
// stays registered and serving for installed apps, which only know it: they
// sign in on it, read /config.js and /release-notes.json from it, and download
// through /api/download on it. Those paths are never redirected away from it.
//
// CANONICAL_HOST is the one address search engines should index. www and
// every Cloudflare Pages address (the project's pages.dev name and each
// deployment's own <id>.<project>.pages.dev, frozen at that build) are copies;
// old copies are how outdated releases stay in search results. Switching
// CANONICAL_HOST to NEW_HOST (scripts/website-hosts.js, with the owner's
// approval) turns on the 301s from legacy pages to the new host.
const LEGACY_HOST = "anxoscontrolcenter.org";
const NEW_HOST = "anxhost.anxlabs.net";
const CANONICAL_HOST = NEW_HOST;

// Sign-in stays on the legacy host until the app and the account service
// trust the new host (Build 217 and a separate approval): the new host sends
// these to the same path on the legacy host.
const AUTH_PAGE = /^\/(?:account|activate|signin|signup|sign-in|sign-up|profile|device|device-login|forgot-password|reset-password)(?:\.html|\/(?:index\.html)?)?$/i;
// Served directly on the legacy host for installed apps and tools.
const LEGACY_DIRECT = /^\/(?:config\.js|release-notes\.json|account-config\.js|marketplace-config\.js|robots\.txt|sitemap\.xml|[0-9a-f]{32}\.txt)$/i;

function isPagePath(pathname) {
  return pathname.endsWith("/") || /\.html?$/i.test(pathname) || !/\.[a-z0-9]{1,8}$/i.test(pathname);
}

function redirect(location, status) {
  return new Response(null, { status, headers: { location, "cache-control": status === 301 ? "public, max-age=3600" : "no-store" } });
}

function routeForHost(url, method) {
  const host = url.hostname.toLowerCase();
  const path = url.pathname;
  const pathAndQuery = `${path}${url.search}`;
  const readOnly = method === "GET" || method === "HEAD";
  if (host === `www.${LEGACY_HOST}` || host === `www.${NEW_HOST}`) {
    const keepOnLegacy = AUTH_PAGE.test(path) || LEGACY_DIRECT.test(path) || path.startsWith("/api/");
    return { redirect: `https://${keepOnLegacy ? LEGACY_HOST : CANONICAL_HOST}${pathAndQuery}`, status: 301 };
  }
  if (host === NEW_HOST && readOnly && AUTH_PAGE.test(path)) {
    return { redirect: `https://${LEGACY_HOST}${pathAndQuery}`, status: 302 };
  }
  if (host === LEGACY_HOST && CANONICAL_HOST !== LEGACY_HOST && readOnly && isPagePath(path) && !AUTH_PAGE.test(path) && !LEGACY_DIRECT.test(path) && !path.startsWith("/api/")) {
    return { redirect: `https://${CANONICAL_HOST}${pathAndQuery}`, status: 301 };
  }
  const noindex = host.endsWith(".pages.dev") || ((host === LEGACY_HOST || host === NEW_HOST) && host !== CANONICAL_HOST);
  return { noindex };
}

export default {
  async fetch(request, env, ctx) {
    const url = new URL(request.url);
    const route = routeForHost(url, request.method);
    if (route.redirect) return redirect(route.redirect, route.status);
    const match = url.pathname.match(/^\/api\/download\/latest\/([^/]+)\/?$/);
    if (request.method === "GET" && match) return latestDownload(request, env, match[1].toLowerCase(), ctx);
    const response = await env.ASSETS.fetch(request);
    if (route.noindex) {
      // Previews, pages.dev and the non-canonical host stay usable but are never indexed.
      const marked = new Response(response.body, response);
      marked.headers.set("x-robots-tag", "noindex, nofollow");
      return marked;
    }
    return response;
  },
};
